"""Единый маршрутизатор запросов.

Зачем он нужен. Каждая область Эрви умеет распознавать себя сама, и это хорошо
работает, пока формулировка привычная. Но у каждой области своя проверка, и между
ними остаются щели: запрос, который не узнал никто, падает в общий планировщик —
и там Эрви теряется, потому что планировщик не знает, к какой области относится
просьба.

Маршрутизатор закрывает именно эти щели. Он вызывается ТОЛЬКО после того, как все
быстрые и надёжные обработчики отказались от хода. Поэтому «выключи пк», пауза и
музыка по-прежнему срабатывают мгновенно и без обращения к модели — до сюда они
просто не доходят. А то, что раньше уходило в планировщик наугад, теперь сначала
получает область.

Шаблонов и регулярных выражений здесь нет: перечислить формулировки невозможно,
и попытка это сделать как раз и создаёт щели, ради которых всё затевалось.
"""

from __future__ import annotations

import json
from typing import Any

from .trace import log_event

# Области и то, что в них входит. Описание идёт в модель как есть, поэтому оно
# написано словами, а не терминами кода.
DOMAINS: dict[str, str] = {
    "mail": "почта: прочитать, разобрать, ответить, написать письмо, спам",
    "telegram": "Telegram: сообщения, чаты, автоответы, мониторинг",
    "phone": "телефон: напоминания, календарь, заметки, звонки, связь с телефоном",
    "video": "видео: монтаж, нарезка, качество, звук, конвертация",
    "media": "проигрыватель: музыка, пауза, громкость, следующий трек",
    "power": "питание: выключить, перезагрузить, сон, блокировка компьютера",
    "files": "файлы и папки: найти, открыть, создать, переместить, удалить",
    "apps": "приложения и сервисы: открыть, запустить, закрыть",
    "food": "еда: калории, продукты, рецепты, заказ, что поесть",
    "code": "код: написать, исправить, объяснить программу или скрипт",
    "screen": "экран: скриншот, что на экране, яркость, окна",
    "web": "интернет: найти информацию, узнать факт, прочитать страницу",
    "task": "многошаговая работа на компьютере, которую надо выполнить",
    "chat": "разговор, вопрос к самой Эрви, всё остальное",
}



# Схема ответа. Ollama принуждает модель выдавать ровно такую форму, поэтому
# разбор перестаёт зависеть от того, добавит ли она пояснение перед JSON.
RESPONSE_SCHEMA: dict[str, object] = {
    "type": "object",
    "properties": {
        "domain": {"type": "string", "enum": sorted(DOMAINS)},
        "confidence": {"type": "number"},
        "restated": {"type": "string"},
        "target": {"type": "string"},
        "needs_clarification": {"type": "boolean"},
        "question": {"type": "string"},
    },
    "required": ["domain", "restated"],
}

class RequestRouter:
    """Определяет область запроса, когда обычные обработчики не сработали."""

    def __init__(self, settings: Any, gateway: Any) -> None:
        self.settings = settings
        self.gateway = gateway

    def classify(self, query: str, context: str = "") -> dict[str, Any]:
        """Область запроса и уточнённая формулировка.

        Модель возвращает не только область, но и переформулировку задачи —
        она нужна обработчику, который дальше работает уже с конкретикой, а не
        с исходной репликой вроде «ну сделай что-нибудь с этим».
        """
        listing = "\n".join(f"- {name}: {what}" for name, what in DOMAINS.items())
        system = (
            "Ты определяешь, к какой области относится просьба владельца компьютера.\n"
            f"Области:\n{listing}\n\n"
            "Верни ТОЛЬКО JSON без пояснений:\n"
            '{"domain": "одно из названий выше", '
            '"confidence": 0.0-1.0, '
            '"restated": "та же просьба, но чётко и конкретно, по-русски", '
            '"target": "к чему относится: имя файла, приложения, человека — если есть", '
            '"needs_clarification": true|false, '
            '"question": "что спросить, если непонятно"}\n\n'
            "domain=chat, если это разговор или вопрос к самой Эрви.\n"
            "domain=task, если нужно что-то сделать на компьютере, "
            "но область точнее не определяется.\n"
            "needs_clarification=true только когда без ответа владельца "
            "действительно нельзя продолжить — лишние переспросы раздражают.\n"
            "restated пишется всегда: это то, с чем дальше будет работать исполнитель.\n\n"
            "Примеры — держись этой логики:\n"
            "«я ещё не завтракал» → food (человек голоден, это про еду)\n"
            "«сколько калорий в сырниках» → food\n"
            "«открой мэш» → apps (мэш, мах, макс — это мессенджер MAX)\n"
            "«врубай ютубчик» → apps\n"
            "«закинь в загрузки» → files\n"
            "«что там по письмам» → mail\n"
            "«напиши Тиме что опоздаю» → telegram\n"
            "«разбуди в семь» → phone (это будильник, а не разговор)\n"
            "«обрежь первые десять секунд» → video\n"
            "«сделай потише» → media\n"
            "«комп выключи через час» → power\n"
            "«почини эту функцию» → code\n"
            "«что сейчас на экране» → screen\n"
            "«кто выиграл вчера» → web (нужен свежий факт из интернета)\n"
            "«как дела» → chat\n"
            "«разберись с этим» → task (надо действовать, но область неясна)\n"
            "«сделай красиво» → нужна ясность: needs_clarification=true"
        )
        user = f"Просьба владельца: {query}"
        if context:
            user += f"\nПоследние реплики:\n{context[:800]}"
        try:
            message = self.gateway.chat(
                [{"role": "system", "content": system}, {"role": "user", "content": user}],
                model=self.settings.fast_model,
                temperature=0.1, think=False,
                response_format=RESPONSE_SCHEMA,
                num_ctx=self.settings.chat_num_ctx, num_predict=260,
            )
            raw = str(message.get("content") or "").strip()
            start, end = raw.find("{"), raw.rfind("}")
            if start >= 0 and end > start:
                data = json.loads(raw[start:end + 1])
                if isinstance(data, dict) and str(data.get("domain")) in DOMAINS:
                    data.setdefault("restated", query)
                    data.setdefault("confidence", 0.5)
                    return data
        except Exception as exc:
            log_event(self.settings.root_dir, "ROUTER_FAILED", error=str(exc)[:200])
        # Отказ маршрутизатора не должен останавливать работу: пусть дальше
        # решает планировщик, как было до его появления.
        return {"domain": "task", "confidence": 0.0, "restated": query}
