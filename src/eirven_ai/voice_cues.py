"""Короткие реплики о ходе работы.

Голосом человек не видит экрана: если между «сделай» и результатом тишина, это
читается как зависание. Одна короткая фраза в начале и одна в конце снимают
вопрос, работает ли ассистент вообще.

Реплики намеренно разные при каждом вызове — одна и та же фраза, повторённая
десять раз подряд, звучит как автоответчик.
"""

from __future__ import annotations

import random

# Начало работы. Подбирается по типу действия: конкретное «Открываю» гораздо
# понятнее общего «Работаю».
_START: dict[str, tuple[str, ...]] = {
    "open_application": ("Открываю.", "Сейчас открою.", "Открываю приложение."),
    "media_control": ("Включаю.", "Секунду.", "Сейчас."),
    "mail_check": ("Смотрю почту.", "Открываю почту.", "Проверяю почту."),
    "mail_send": ("Готовлю письмо.", "Пишу письмо."),
    "telegram_send": ("Пишу в Telegram.", "Отправляю сообщение."),
    "telegram_monitor": ("Настраиваю мониторинг.", "Включаю автоответы."),
    "reminder": ("Ставлю напоминание.", "Записываю в календарь."),
    "video_edit": ("Берусь за видео.", "Начинаю монтаж."),
    "vision_direct": ("Смотрю.", "Сейчас разгляжу."),
    "pc_shutdown_confirmation": ("Готовлю выключение.",),
    "teaching_started": ("Записываю. Показывай.",),
}
_START_DEFAULT = ("Выполняю.", "Делаю.", "Сейчас сделаю.", "Берусь.")

# Завершение. Короткое подтверждение — этого достаточно, детали уже в чате.
_DONE = ("Готово.", "Сделано.", "Всё, готово.", "Выполнила.")

# Неудача. Без оправданий и без обещаний, которые может быть некому выполнить:
# «меня научат в следующих обновлениях» — это обещание от лица продукта, и если
# обновление не выйдет, фраза превращается в обман. Здесь честная констатация и
# понятный следующий шаг.
_FAILED = (
    "Не получилось. Показала в чате, что удалось сделать.",
    "Не вышло. Подробности в чате.",
    "Не справилась с этим. В чате написала почему.",
)

# Неудача, но найдены материалы — отдельный случай, звучит полезнее.
_FAILED_WITH_LINKS = (
    "Сама не смогла, но нашла подходящие ссылки — они в чате.",
    "Не получилось, зато собрала ссылки по теме. Загляни в чат.",
)

# Можно научить — предлагаем показать, вместо тупика.
_FAILED_TEACHABLE = (
    "Не получилось. Нажми «Обучить выполнению» в чате, чтобы показать нужные шаги.",
    "Пока не умею. Покажешь один раз — запомню.",
)

_MIN_SECONDS_TO_ANNOUNCE = 1.2


def start_cue(action: str = "") -> str:
    """Что сказать, берясь за задачу."""
    return random.choice(_START.get(str(action or ""), _START_DEFAULT))


def done_cue() -> str:
    return random.choice(_DONE)


def failed_cue(*, has_links: bool = False, teachable: bool = False) -> str:
    if teachable:
        return random.choice(_FAILED_TEACHABLE)
    if has_links:
        return random.choice(_FAILED_WITH_LINKS)
    return random.choice(_FAILED)


def should_announce(action: str, expected_seconds: float = 0.0) -> bool:
    """Стоит ли вообще открывать рот.

    На мгновенных ответах реплика мешает: человек услышит «Выполняю» и сразу
    следом сам ответ. Озвучиваем только то, что действительно займёт время.
    """
    if not action or action in {"chat", "instant", "creator_identity"}:
        return False
    return expected_seconds >= _MIN_SECONDS_TO_ANNOUNCE or action in _START
